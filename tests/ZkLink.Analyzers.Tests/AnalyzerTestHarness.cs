using System.Collections.Immutable;
using Microsoft.CodeAnalysis;
using Microsoft.CodeAnalysis.CSharp;
using Microsoft.CodeAnalysis.Diagnostics;

namespace ZkLink.Analyzers.Tests;

internal static class AnalyzerTestHarness
{
    internal static async Task<Diagnostic[]> AnalyzeAsync(
        string source,
        params DiagnosticAnalyzer[] analyzers
    ) => await AnalyzeAsync(source, "Test.cs", analyzers).ConfigureAwait(true);

    internal static async Task<Diagnostic[]> AnalyzeGeneratedAsync(
        string source,
        params DiagnosticAnalyzer[] analyzers
    ) =>
        await AnalyzeAsync("// <auto-generated/>\n" + source, "Test.cs", analyzers)
            .ConfigureAwait(true);

    private static async Task<Diagnostic[]> AnalyzeAsync(
        string source,
        string path,
        DiagnosticAnalyzer[] analyzers
    )
    {
        var compilation = CSharpCompilation.Create(
            "ZkLink.Analyzers.Tests.Target",
            [
                CSharpSyntaxTree.ParseText(
                    ZkLinkStubs,
                    CSharpParseOptions.Default.WithLanguageVersion(LanguageVersion.CSharp14),
                    path: "Stubs.cs"
                ),
                CSharpSyntaxTree.ParseText(
                    source,
                    CSharpParseOptions.Default.WithLanguageVersion(LanguageVersion.CSharp14),
                    path: path
                ),
            ],
            CreateReferences(),
            new CSharpCompilationOptions(OutputKind.DynamicallyLinkedLibrary)
        );

        Assert.DoesNotContain(
            compilation.GetDiagnostics(),
            diagnostic => diagnostic.Severity == DiagnosticSeverity.Error
        );

        ImmutableArray<Diagnostic> diagnostics = await compilation
            .WithAnalyzers([.. analyzers])
            .GetAnalyzerDiagnosticsAsync()
            .ConfigureAwait(true);
        return diagnostics.OrderBy(diagnostic => diagnostic.Id, StringComparer.Ordinal).ToArray();
    }

    private static MetadataReference[] CreateReferences()
    {
        var trustedPlatformAssemblies =
            (string?)AppContext.GetData("TRUSTED_PLATFORM_ASSEMBLIES") ?? string.Empty;
        return trustedPlatformAssemblies
            .Split(Path.PathSeparator, StringSplitOptions.RemoveEmptyEntries)
            .Select(path => MetadataReference.CreateFromFile(path))
            .ToArray();
    }

    private const string ZkLinkStubs = """
        namespace ZkLink
        {
            public sealed class ZooKeeperAuthentication
            {
                public static ZooKeeperAuthentication Digest(string userName, string password) => new();
            }

            public sealed class ZooKeeperClientOptions
            {
                public required string ConnectionString { get; init; }
                public bool AllowUnsafePlaintextDigest { get; init; }
            }

            public enum PersistentWatchMode
            {
                Persistent,
                PersistentRecursive
            }

            public sealed class WatchedResult<T>
            {
                public WatchedResult(T value, ZooKeeperWatch watch)
                {
                    Value = value;
                    Watch = watch;
                }

                public T Value { get; }
                public ZooKeeperWatch Watch { get; }
            }

            public sealed class ZooKeeperWatch : System.IAsyncDisposable
            {
                public System.Threading.Tasks.Task RemoveAsync(
                    System.Threading.CancellationToken cancellationToken = default) =>
                    System.Threading.Tasks.Task.CompletedTask;

                public System.Threading.Tasks.ValueTask DisposeAsync() => default;
            }

            public sealed class ZooKeeperClient : System.IAsyncDisposable
            {
                public static System.Threading.Tasks.Task<ZooKeeperClient> ConnectAsync(
                    ZooKeeperClientOptions options,
                    System.Threading.CancellationToken cancellationToken = default) =>
                    System.Threading.Tasks.Task.FromResult(new ZooKeeperClient());

                public System.Threading.Tasks.Task SyncAsync(
                    string path,
                    System.Threading.CancellationToken cancellationToken = default) =>
                    System.Threading.Tasks.Task.CompletedTask;

                public System.Threading.Tasks.Task<string> GetDataAsync(
                    string path,
                    System.Threading.CancellationToken cancellationToken = default) =>
                    System.Threading.Tasks.Task.FromResult(string.Empty);

                public System.Threading.Tasks.Task<ZooKeeperWatch> AddWatchAsync(
                    string path,
                    PersistentWatchMode mode,
                    System.Threading.CancellationToken cancellationToken = default) =>
                    System.Threading.Tasks.Task.FromResult(new ZooKeeperWatch());

                public System.Threading.Tasks.Task<WatchedResult<string>> ExistsAndWatchAsync(
                    string path,
                    System.Threading.CancellationToken cancellationToken = default) =>
                    System.Threading.Tasks.Task.FromResult(
                        new WatchedResult<string>(string.Empty, new ZooKeeperWatch()));

                public System.Threading.Tasks.Task<WatchedResult<string>> GetDataAndWatchAsync(
                    string path,
                    System.Threading.CancellationToken cancellationToken = default) =>
                    System.Threading.Tasks.Task.FromResult(
                        new WatchedResult<string>(string.Empty, new ZooKeeperWatch()));

                public System.Threading.Tasks.Task<WatchedResult<string>> GetChildrenAndWatchAsync(
                    string path,
                    System.Threading.CancellationToken cancellationToken = default) =>
                    System.Threading.Tasks.Task.FromResult(
                        new WatchedResult<string>(string.Empty, new ZooKeeperWatch()));

                public System.Threading.Tasks.ValueTask DisposeAsync() => default;
            }
        }

        """;
}
